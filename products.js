window.IaraShop = (() => {
  const CART_KEY = "iara-cart";
  const WISHLIST_KEY = "iara-wishlist";
  const read = (key) => {
    try { return JSON.parse(localStorage.getItem(key) || "[]"); }
    catch { return []; }
  };
  const write = (key, value) => localStorage.setItem(key, JSON.stringify(value));
  const normalizeEntry = (entry) => typeof entry === "number" ? { id: entry, size: "" } : { id: Number(entry.id), size: entry.size || "" };
  const find = (id) => window.IARA_PRODUCTS.find((product) => product.id === Number(id));
  return {
    formatPrice(value) { return `HK$${Number(value).toLocaleString("en-HK")}`; },
    getCartIds() { return read(CART_KEY); },
    getCart() { return read(CART_KEY).map(normalizeEntry).map((entry) => { const product = find(entry.id); return product ? { ...product, selectedSize: entry.size } : null; }).filter(Boolean); },
    addCart(id, options = {}) { const cart = read(CART_KEY); cart.push({ id: Number(id), size: options.size || "" }); write(CART_KEY, cart); return cart; },
    removeCart(index) { const cart = read(CART_KEY); cart.splice(Number(index), 1); write(CART_KEY, cart); return cart; },
    getWishlist() { return new Set(read(WISHLIST_KEY).map(Number)); },
    toggleWishlist(id) {
      const wishlist = new Set(read(WISHLIST_KEY).map(Number));
      const productId = Number(id);
      wishlist.has(productId) ? wishlist.delete(productId) : wishlist.add(productId);
      write(WISHLIST_KEY, [...wishlist]);
      return wishlist;
    }
  };
})();
